def get_all_indian_sources() -> List[IndianSourceTarget]:
    """Returns the complete list of all 110+ curated Indian source targets."""
    return list(INDIAN_SOURCE_INVENTORY.values())


def get_sources_by_category(category: str) -> List[IndianSourceTarget]:
    """Filters sources by category code (e.g. A_GOV_REGULATORY, C_FINANCIAL, etc.)."""
    return [s for s in INDIAN_SOURCE_INVENTORY.values() if s.category == category]


def get_indian_source_by_id(source_id: str) -> Optional[IndianSourceTarget]:
    """Looks up a single source target by its stable ID."""
    return INDIAN_SOURCE_INVENTORY.get(source_id)


def get_inventory_summary() -> Dict[str, any]:
    """Computes real verified counts across all categories and execution types."""
    total = len(INDIAN_SOURCE_INVENTORY)
    by_category: Dict[str, int] = {}
    by_exec_type: Dict[str, int] = {}
    by_status: Dict[str, int] = {}

    for s in INDIAN_SOURCE_INVENTORY.values():
        by_category[s.category] = by_category.get(s.category, 0) + 1
        by_exec_type[s.execution_type] = by_exec_type.get(s.execution_type, 0) + 1
        by_status[s.verification_status] = by_status.get(s.verification_status, 0) + 1

    return {
        "total_sources": total,
        "by_category": by_category,
        "by_execution_type": by_exec_type,
        "by_verification_status": by_status,
        "last_verified": NOW_VERIFIED,
    }

